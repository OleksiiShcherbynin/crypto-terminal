/** Raw Binance payloads; all numeric price/volume fields arrive as strings. */
export interface RawMiniTicker {
  e: '24hrMiniTicker';
  E: number;
  s: string;
  c: string;
  o: string;
  h: string;
  l: string;
  v: string;
  q: string;
}

export interface RawKline {
  e: 'kline';
  E: number;
  s: string;
  k: {
    t: number;
    T: number;
    s: string;
    i: string;
    o: string;
    c: string;
    h: string;
    l: string;
    v: string;
    x: boolean;
  };
}

export interface RawCombined {
  stream: string;
  data: RawMiniTicker | RawKline;
}
